# pandas 라이브러리를 불러온다
import pandas as pd

# 시설명과 가격 열을 가진 가상의 예시 데이터를 만든다
data = {
    "시설명": ["가짜요가원A", "가짜요가원B", "가짜요가원C"],
    "가격": [55000, 89000, 120000],
}

# 딕셔너리를 데이터프레임으로 변환한다
df = pd.DataFrame(data)

# 표 위에 안내 문구를 출력한다
print("환경 확인용 가상 예시")

# 데이터프레임 표를 출력한다
print(df)

# 데이터프레임의 행/열 개수(shape)를 출력한다
print(df.shape)
